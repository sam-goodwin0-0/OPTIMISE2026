class Problem:
    """A smooth unconstrained optimisation problem with a strict call budget."""

    SAFETY_LIMIT = 1.0e8

    def __init__(
        self,
        *,
        n: int,
        x0: np.ndarray,
        budget: int,
        seed: int,
        value_fn: Callable[[np.ndarray], float],
        gradient_fn: Optional[Callable[[np.ndarray], np.ndarray]] = None,
    ) -> None:
        if n <= 0:
            raise ValueError("n must be positive")
        if budget <= 0:
            raise ValueError("budget must be positive")
        self.n = int(n)
        self.x0 = self._coerce_point(x0).copy()
        self.budget = int(budget)
        self.seed = int(seed)
        self.has_gradient = gradient_fn is not None
        self._value_fn = value_fn
        self._gradient_fn = gradient_fn
        self._used = 0
        self._value_calls = 0
        self._gradient_calls = 0
        self._invalid_calls = 0

    @property
    def remaining(self) -> int:
        return self.budget - self._used

    @property
    def used(self) -> int:
        return self._used

    @property
    def value_calls(self) -> int:
        return self._value_calls

    @property
    def gradient_calls(self) -> int:
        return self._gradient_calls

    @property
    def invalid_calls(self) -> int:
        return self._invalid_calls

    def _coerce_point(self, x: np.ndarray) -> np.ndarray:
        try:
            arr = np.asarray(x, dtype=float)
        except Exception as exc:  # pragma: no cover - defensive
            raise InvalidPoint("point is not numeric") from exc
        if arr.ndim != 1 or arr.shape[0] != self.n:
            raise InvalidPoint(f"expected shape ({self.n},), received {arr.shape}")
        if not np.all(np.isfinite(arr)):
            raise InvalidPoint("point contains NaN or infinity")
        if np.max(np.abs(arr), initial=0.0) > self.SAFETY_LIMIT:
            raise InvalidPoint("point exceeds the numerical safety limit")
        return arr

    def _charge(self, units: int) -> None:
        if self.remaining < units:
            raise BudgetExceeded(
                f"oracle call costs {units} units but only {self.remaining} remain"
            )
        self._used += units

    def value(self, x: np.ndarray) -> float:
        try:
            arr = self._coerce_point(x)
        except InvalidPoint:
            self._invalid_calls += 1
            raise
        self._charge(1)
        self._value_calls += 1
        value = float(self._value_fn(arr.copy()))
        if not np.isfinite(value):
            raise InvalidPoint("objective returned a non-finite value")
        return value

    def gradient(self, x: np.ndarray) -> np.ndarray:
        if self._gradient_fn is None:
            raise GradientUnavailable("this instance does not expose a gradient")
        try:
            arr = self._coerce_point(x)
        except InvalidPoint:
            self._invalid_calls += 1
            raise
        self._charge(2)
        self._gradient_calls += 1
        grad = np.asarray(self._gradient_fn(arr.copy()), dtype=float)
        if grad.shape != (self.n,):
            raise RuntimeError("internal benchmark gradient has the wrong shape")
        if not np.all(np.isfinite(grad)):
            raise InvalidPoint("gradient returned a non-finite value")
        return grad.copy()

    def evaluate_untimed(self, x: np.ndarray) -> float:
        """Evaluate the objective without charging the budget (organiser only)."""
        return float(self._value_fn(self._coerce_point(x)))


