def load_student_solver(path: str | Path, *, enforce: bool = True):
    """Compile and execute ``solver.py`` in a restricted namespace.

    Returns the team's ``solve`` callable. Raises :class:`SubmissionError` with a
    message that is safe to show to the team.
    """
    solver_path = Path(path)
    if not solver_path.is_file():
        raise SubmissionError(f"solver.py was not found at {solver_path.name}")

    if enforce:
        issues = static_check(solver_path)
        if issues:
            raise SubmissionError("submission rejected by the rule check: " + "; ".join(issues))

    source = solver_path.read_text(encoding="utf-8", errors="replace")
    try:
        code = compile(source, "solver.py", "exec")
    except SyntaxError as exc:
        raise SubmissionError(f"syntax error on line {exc.lineno}: {exc.msg}") from exc

    module = types.ModuleType("team_solver")
    module.__dict__["__name__"] = "team_solver"
    module.__dict__["__file__"] = "solver.py"
    if enforce:
        module.__dict__["__builtins__"] = _build_restricted_builtins()

    # dataclasses and typing resolve annotations through sys.modules[cls.__module__],
    # so the module must be registered. "team_solver" is not an importable name
    # under the restricted import hook, so this grants the submission nothing.
    import sys

    sys.modules["team_solver"] = module

    try:
        exec(code, module.__dict__)  # noqa: S102 - deliberate, sandboxed above
    except Exception as exc:
        raise SubmissionError(f"solver.py failed while being imported: {type(exc).__name__}: {exc}") from exc

    solve = module.__dict__.get("solve")
    if not callable(solve):
        raise SubmissionError("solver.py must define a callable solve(problem)")
    return solve



# ---------------------------------------------------------------------------
# Make both documented import styles work inside a team's solver.py, exactly as
# they do on the platform:
#     from optimise import BudgetExceeded
#     from Framework.optimise import BudgetExceeded
# ---------------------------------------------------------------------------

def _install_import_shims() -> None:
    shim = types.ModuleType("optimise")
    for name in ("BudgetExceeded", "GradientUnavailable", "InvalidPoint"):
        setattr(shim, name, globals()[name])
    sys.modules["optimise"] = shim

    package = types.ModuleType("Framework")
    package.__path__ = []
    inner = types.ModuleType("Framework.optimise")
    for name in ("BudgetExceeded", "GradientUnavailable", "InvalidPoint"):
        setattr(inner, name, globals()[name])
    package.optimise = inner
    sys.modules["Framework"] = package
    sys.modules["Framework.optimise"] = inner


