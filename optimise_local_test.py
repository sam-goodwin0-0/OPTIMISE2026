def _safe_getattr(obj, name, *default):
    if isinstance(name, str) and name.startswith("_"):
        raise AttributeError(f"access to private attribute '{name}' is not permitted")
    return getattr(obj, name, *default)


def _safe_hasattr(obj, name):
    if isinstance(name, str) and name.startswith("_"):
        return False
    return hasattr(obj, name)


def _build_restricted_builtins() -> dict:
    namespace = {}
    for name in _ALLOWED_BUILTINS:
        if hasattr(_builtins, name):
            namespace[name] = getattr(_builtins, name)
    namespace["__import__"] = _restricted_import
    namespace["getattr"] = _safe_getattr
    namespace["hasattr"] = _safe_hasattr
    return namespace


