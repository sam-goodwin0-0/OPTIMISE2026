def main() -> int:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(
        description="Score your solver on the public practice suite (P01-P08).")
    parser.add_argument("--solver", default=None,
                        help="path to your solver.py (default: solver.py next to this file)")
    parser.add_argument("--quiet", action="store_true", help="print the summary only")
    parser.add_argument("--no-rule-check", action="store_true",
                        help="skip the import rule check (the platform will still apply it)")
    args = parser.parse_args()

    if args.solver:
        solver = Path(args.solver)
        if not solver.is_file():
            solver = here / args.solver
    else:
        solver = here / "solver.py"
    if not solver.is_file():
        print(f"Could not find solver.py.\nLooked for: {solver}", file=sys.stderr)
        print("Put this file in the same folder as your solver.py, or pass --solver.",
              file=sys.stderr)
        return 2

    _install_import_shims()
    if not args.no_rule_check:
        harden_numpy()

    try:
        solve = load_student_solver(solver, enforce=not args.no_rule_check)
    except SubmissionError as exc:
        print("Your solver was REJECTED by the competition rule check:\n", file=sys.stderr)
        print(f"    {exc}\n", file=sys.stderr)
        print("The platform applies the same check, so fix this before submitting.",
              file=sys.stderr)
        return 1

    rows = []
    started = time.time()
    for config in PUBLIC_INSTANCES:
        problem, reference = build_problem(config)
        view = make_view(problem)
        error, f_final, valid = "", float("inf"), False
        try:
            raw = solve(view)
            if not isinstance(raw, dict):
                raise TypeError("solve(problem) must return a dictionary")
            missing = {"x", "status", "method"} - set(raw)
            if missing:
                raise KeyError(f"missing return keys: {sorted(missing)}")
            x = np.asarray(raw["x"], dtype=float)
            if x.shape != (problem.n,):
                raise ValueError(
                    f"result['x'] must have shape ({problem.n},), got {x.shape}")
            f_final = problem.evaluate_untimed(x)
            if not np.isfinite(f_final):
                raise ValueError("the objective at your returned point is not finite")
            valid = True
        except Exception as exc:
            error = f"{type(exc).__name__}: {exc}"

        info = instance_score(f0=reference.initial_value,
                              f_star=reference.reference_value,
                              f_final=f_final, used=problem.used,
                              budget=problem.budget, valid=valid)
        rows.append({"instance_id": reference.instance_id, "family": reference.family,
                     "n": problem.n, "budget": problem.budget, "used": problem.used,
                     "valid": valid, "error": error, **info})

    summary = aggregate_scores(rows)
    elapsed = time.time() - started

    if not args.quiet:
        print(f"{'id':<5}{'family':<17}{'n':>3}{'budget':>8}{'used':>7}"
              f"{'valid':>7}{'quality':>9}{'score':>8}  note")
        for r in rows:
            note = r["error"] or ("high accuracy" if r["accurate"] else "")
            print(f"{r['instance_id']:<5}{r['family']:<17}{r['n']:>3}{r['budget']:>8}"
                  f"{r['used']:>7}{'yes' if r['valid'] else 'NO':>7}"
                  f"{r['quality']:>9.3f}{r['score']:>8.2f}  {note}")
        print()

    print("OPTIMISE@Wits public practice suite (P01-P08)")
    print(f"  Overall score:       {summary['overall']:.2f}")
    print(f"  Mean instance score: {summary['mean']:.2f}")
    print(f"  Lower quartile:      {summary['lower_quartile']:.2f}")
    print(f"  Valid instances:     {summary['valid_instances']}/{len(rows)}")
    print(f"  High accuracy:       {summary['accurate_instances']}/{len(rows)}")
    print(f"  Time taken:          {elapsed:.1f}s")

    if summary["valid_instances"] < len(rows):
        print("\nSome instances are INVALID. An invalid instance scores zero on the")
        print("platform too, so fix these before you submit.")
        return 1
    return 0


