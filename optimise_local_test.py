def build_problem(config: dict) -> Tuple[Problem, ReferenceData]:
    """Construct a student-facing Problem and staff-only reference data."""
    family = str(config["family"])
    n = int(config["n"])
    seed = int(config["seed"])
    budget = int(config["budget"])
    provide_gradient = bool(config.get("gradient", True))
    condition = float(config.get("condition", 1.0))
    amplitude = float(config.get("amplitude", 1.0))
    offset = float(config.get("offset", 0.0))
    rotation = bool(config.get("rotation", True))
    shift_scale = float(config.get("shift_scale", 2.0))

    rng = np.random.default_rng(seed)
    if family not in _BUILDERS:
        raise KeyError(f"unknown benchmark family: {family}")
    base = _BUILDERS[family](n, rng)

    q = _orthogonal(n, rng) if rotation else np.eye(n)
    if condition <= 1.0:
        scales = np.ones(n)
    else:
        scales = np.geomspace(1.0, np.sqrt(condition), n)
        rng.shuffle(scales)
    a_matrix = np.diag(scales) @ q
    shift = rng.normal(scale=shift_scale, size=n)

    def to_y(x: Array) -> Array:
        return a_matrix @ (x - shift)

    def value_fn(x: Array) -> float:
        return amplitude * base.value(to_y(x)) + offset

    def gradient_fn(x: Array) -> Array:
        return amplitude * a_matrix.T @ base.gradient(to_y(x))

    x_star = shift + np.linalg.solve(a_matrix, base.optimum_y)
    x0 = shift + np.linalg.solve(a_matrix, base.initial_y)
    f_star = amplitude * base.optimum_value + offset
    f0 = value_fn(x0)
    instance_id = str(config["id"])
    reference = ReferenceData(
        instance_id=instance_id,
        family=family,
        x_star=x_star.copy(),
        reference_value=float(f_star),
        initial_value=float(f0),
    )

    problem = Problem(
        n=n,
        x0=x0,
        budget=budget,
        seed=seed + 100_003,
        value_fn=value_fn,
        gradient_fn=gradient_fn if provide_gradient else None,
    )
    return problem, reference

