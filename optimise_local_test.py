def _orthogonal(n: int, rng: np.random.Generator) -> Array:
    q, r = np.linalg.qr(rng.normal(size=(n, n)))
    signs = np.sign(np.diag(r))
    signs[signs == 0.0] = 1.0
    return q @ np.diag(signs)


def _sphere(n: int, rng: np.random.Generator) -> BaseSpec:
    y0 = rng.normal(size=n) * 4.0
    return BaseSpec(
        value=lambda y: 0.5 * float(y @ y),
        gradient=lambda y: y.copy(),
        optimum_y=np.zeros(n),
        optimum_value=0.0,
        initial_y=y0,
    )


def _rosenbrock(n: int, rng: np.random.Generator) -> BaseSpec:
    if n < 2:
        raise ValueError("Rosenbrock requires n >= 2")

    def value(y: Array) -> float:
        return float(np.sum(100.0 * (y[1:] - y[:-1] ** 2) ** 2 + (1.0 - y[:-1]) ** 2))

    def gradient(y: Array) -> Array:
        g = np.zeros_like(y)
        g[:-1] += -400.0 * y[:-1] * (y[1:] - y[:-1] ** 2) - 2.0 * (1.0 - y[:-1])
        g[1:] += 200.0 * (y[1:] - y[:-1] ** 2)
        return g

    y0 = np.ones(n)
    y0[::2] = -1.2
    return BaseSpec(value, gradient, np.ones(n), 0.0, y0)


def _powell(n: int, rng: np.random.Generator) -> BaseSpec:
    if n % 4 != 0:
        raise ValueError("Powell dimension must be a multiple of four")

    def value(y: Array) -> float:
        z = y.reshape(-1, 4)
        t1 = z[:, 0] + 10.0 * z[:, 1]
        t2 = z[:, 2] - z[:, 3]
        t3 = z[:, 1] - 2.0 * z[:, 2]
        t4 = z[:, 0] - z[:, 3]
        return float(np.sum(t1**2 + 5.0 * t2**2 + t3**4 + 10.0 * t4**4))

    def gradient(y: Array) -> Array:
        z = y.reshape(-1, 4)
        g = np.zeros_like(z)
        t1 = z[:, 0] + 10.0 * z[:, 1]
        t2 = z[:, 2] - z[:, 3]
        t3 = z[:, 1] - 2.0 * z[:, 2]
        t4 = z[:, 0] - z[:, 3]
        g[:, 0] = 2.0 * t1 + 40.0 * t4**3
        g[:, 1] = 20.0 * t1 + 4.0 * t3**3
        g[:, 2] = 10.0 * t2 - 8.0 * t3**3
        g[:, 3] = -10.0 * t2 - 40.0 * t4**3
        return g.reshape(-1)

    y0 = np.tile(np.array([3.0, -1.0, 0.0, 1.0]), n // 4)
    return BaseSpec(value, gradient, np.zeros(n), 0.0, y0)


def _wood(n: int, rng: np.random.Generator) -> BaseSpec:
    if n % 4 != 0:
        raise ValueError("Wood dimension must be a multiple of four")

    def value(y: Array) -> float:
        z = y.reshape(-1, 4)
        x1, x2, x3, x4 = z.T
        block = (
            100.0 * (x2 - x1**2) ** 2
            + (1.0 - x1) ** 2
            + 90.0 * (x4 - x3**2) ** 2
            + (1.0 - x3) ** 2
            + 10.1 * ((x2 - 1.0) ** 2 + (x4 - 1.0) ** 2)
            + 19.8 * (x2 - 1.0) * (x4 - 1.0)
        )
        return float(np.sum(block))

    def gradient(y: Array) -> Array:
        z = y.reshape(-1, 4)
        x1, x2, x3, x4 = z.T
        g = np.empty_like(z)
        g[:, 0] = -400.0 * x1 * (x2 - x1**2) - 2.0 * (1.0 - x1)
        g[:, 1] = 200.0 * (x2 - x1**2) + 20.2 * (x2 - 1.0) + 19.8 * (x4 - 1.0)
        g[:, 2] = -360.0 * x3 * (x4 - x3**2) - 2.0 * (1.0 - x3)
        g[:, 3] = 180.0 * (x4 - x3**2) + 20.2 * (x4 - 1.0) + 19.8 * (x2 - 1.0)
        return g.reshape(-1)

    y0 = np.tile(np.array([-3.0, -1.0, -3.0, -1.0]), n // 4)
    return BaseSpec(value, gradient, np.ones(n), 0.0, y0)


def _ripple(n: int, rng: np.random.Generator) -> BaseSpec:
    def value(y: Array) -> float:
        return float(np.sum(y**2 + 0.10 * (1.0 - np.cos(5.0 * y))))

    def gradient(y: Array) -> Array:
        return 2.0 * y + 0.5 * np.sin(5.0 * y)

    y0 = rng.uniform(-4.0, 4.0, size=n)
    return BaseSpec(value, gradient, np.zeros(n), 0.0, y0)


def _twisted_quartic(n: int, rng: np.random.Generator) -> BaseSpec:
    def value(y: Array) -> float:
        coupling = 0.05 * np.sum((y[1:] - y[:-1]) ** 2)
        return float(np.sum((y**2 - 1.0) ** 2) + coupling)

    def gradient(y: Array) -> Array:
        g = 4.0 * y * (y**2 - 1.0)
        if n > 1:
            diff = y[1:] - y[:-1]
            g[:-1] -= 0.10 * diff
            g[1:] += 0.10 * diff
        return g

    y0 = rng.normal(scale=0.35, size=n)
    return BaseSpec(value, gradient, np.ones(n), 0.0, y0)


def _styblinski(n: int, rng: np.random.Generator) -> BaseSpec:
    optimum_scalar = -2.903534027771178
    optimum_value = -39.16616570377142 * n

    def value(y: Array) -> float:
        return float(0.5 * np.sum(y**4 - 16.0 * y**2 + 5.0 * y))

    def gradient(y: Array) -> Array:
        return 2.0 * y**3 - 16.0 * y + 2.5

    y0 = rng.uniform(-1.0, 3.5, size=n)
    return BaseSpec(
        value,
        gradient,
        np.full(n, optimum_scalar),
        optimum_value,
        y0,
    )


def _plateau(n: int, rng: np.random.Generator) -> BaseSpec:
    eps = 1.0e-4

    def value(y: Array) -> float:
        return float(np.sum(np.sqrt(y**2 + eps) - np.sqrt(eps)))

    def gradient(y: Array) -> Array:
        return y / np.sqrt(y**2 + eps)

    y0 = rng.normal(size=n) * 5.0
    return BaseSpec(value, gradient, np.zeros(n), 0.0, y0)


def _himmelblau(n: int, rng: np.random.Generator) -> BaseSpec:
    if n != 2:
        raise ValueError("Himmelblau is two-dimensional")

    def value(y: Array) -> float:
        a = y[0] ** 2 + y[1] - 11.0
        b = y[0] + y[1] ** 2 - 7.0
        return float(a**2 + b**2)

    def gradient(y: Array) -> Array:
        a = y[0] ** 2 + y[1] - 11.0
        b = y[0] + y[1] ** 2 - 7.0
        return np.array([4.0 * y[0] * a + 2.0 * b, 2.0 * a + 4.0 * y[1] * b])

    # One known global minimiser; the transformed function retains several.
    optimum = np.array([3.0, 2.0])
    y0 = np.array([-4.0, 0.0])
    return BaseSpec(value, gradient, optimum, 0.0, y0)


