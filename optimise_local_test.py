import math
from typing import Iterable

import numpy as np

EPS = 1.0e-12


def instance_score(*, f0: float, f_star: float, f_final: float,
                   used: int, budget: int, valid: bool) -> dict:
    if not valid or not all(map(math.isfinite, (f0, f_star, f_final))):
        return {"quality": 0.0, "efficiency": 0.0, "score": 0.0, "accurate": False}
    g0 = max(float(f0 - f_star), EPS)
    gt = max(float(f_final - f_star), EPS)
    log_progress = math.log10(g0 / gt)
    quality = float(np.clip(log_progress / 8.0, 0.0, 1.0))
    efficiency = quality * max(0.0, 1.0 - float(used) / max(float(budget), 1.0))
    score = 95.0 * quality + 5.0 * efficiency
    return {
        "quality": quality,
        "efficiency": efficiency,
        "score": score,
        "accurate": quality >= 0.90,
    }


def aggregate_scores(instance_results: Iterable[dict]) -> dict:
    rows = list(instance_results)
    if not rows:
        return {
            "overall": 0.0,
            "mean": 0.0,
            "lower_quartile": 0.0,
            "valid_instances": 0,
            "accurate_instances": 0,
            "total_used": 0,
        }
    scores = np.array([float(r.get("score", 0.0)) for r in rows], dtype=float)
    mean = float(np.mean(scores))
    lower_quartile = float(np.quantile(scores, 0.25))
    overall = 0.8 * mean + 0.2 * lower_quartile
    return {
        "overall": overall,
        "mean": mean,
        "lower_quartile": lower_quartile,
        "valid_instances": sum(bool(r.get("valid", False)) for r in rows),
        "accurate_instances": sum(bool(r.get("accurate", False)) for r in rows),
        "total_used": sum(int(r.get("used", 0)) for r in rows),
    }

