def _module_allowed(name: str) -> bool:
    root = name.split(".")[0]
    if root == "numpy":
        return name not in _BLOCKED_NUMPY_SUBMODULES
    if root == "collections":  # collections.abc only
        return name in {"collections", "collections.abc"}
    if root == "Framework":
        return name in {"Framework", "Framework.optimise"}
    return name in ALLOWED_MODULES


def _restricted_import(name, globals=None, locals=None, fromlist=(), level=0):
    if level != 0:
        raise ImportError("relative imports are not permitted in solver.py")
    if not _module_allowed(name):
        raise ImportError(f"import of '{name}' is not permitted; {_BLOCKED_MODULE_HINT}")
    module = importlib.import_module(name)
    if fromlist:
        for item in fromlist:
            candidate = f"{name}.{item}"
            if isinstance(item, str) and not hasattr(module, item):
                if not _module_allowed(candidate):
                    raise ImportError(
                        f"import of '{candidate}' is not permitted; {_BLOCKED_MODULE_HINT}"
                    )
                importlib.import_module(candidate)
        return module
    # ``import a.b`` binds the root package.
    return importlib.import_module(name.split(".")[0])


